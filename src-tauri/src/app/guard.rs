//! Сторож соединения (D-107): правда ли трафик идёт через туннель.
//!
//! Ядро может работать, а VPN — нет: узел умер, провайдер зарезал транспорт, сеть
//! сменилась под ногами. Окно при этом зелёное, потому что зелёный цвет отвечает
//! за живость процесса, а не за то, что через него что-то едет.
//!
//! Проба здесь не своя: это `diag::web::whoami` — та же, что стоит за «Внешним адресом».
//! Сторож — это она плюс расписание и одна строка в статус (D-105 про то же).
//!
//! Жалоба принадлежит **тому ядру**, на котором получена: поднятое заново — чистый лист,
//! и висящая с прошлой жизни строка не переживёт переподключения. Отсюда `about_core`:
//! рядом с текстом лежит отметка запуска. Живёт жалоба в общем реестре (`app::notice`) —
//! сторож у него не единственный писатель.

use crate::app::notice::{Notice, GUARD};
use crate::app::state::AppState;
use crate::diag::web::WebProbe;

pub struct Guard;

impl Guard {
    /// Посмотреть, идёт ли трафик, и запомнить ответ. Ядро не работает — жалоб быть
    /// не может: сторож про туннель, а не про то, что его нет.
    ///
    /// В TUN идём напрямую: там перехвачен весь трафик машины, и обычный запрос **и есть**
    /// запрос через туннель. В local — через порт прокси, иначе замерили бы домашний канал.
    pub async fn look(state: &AppState) {
        let core = state.mihomo.status();
        let Some(since) = core.started.filter(|_| core.running) else {
            state.notices.set(GUARD, None);
            return;
        };
        let seen = WebProbe::whoami(core.port).await;
        state.notices.set(
            GUARD,
            seen.is_none().then(|| {
                Notice::about_core(
                    "Ядро работает, но наружу через него ничего не проходит — узел молчит.",
                    since,
                )
            }),
        );
    }
}
